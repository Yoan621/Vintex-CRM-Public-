/**
 * Utilitaires pour générer des dates dynamiques
 */
const getDaysAgo = (days: number): Date => {
  const date = new Date()
  date.setDate(date.getDate() - days)
  return date
}

/**
 * Fonction pour filtrer les ventes par période temporelle
 */
export function filterOrdersByPeriod(orders: Order[], period: 'day' | 'week' | 'month' | 'year'): Order[] {
  const now = new Date()
  const startOfPeriod = new Date()

  switch (period) {
    case 'day':
      // Aujourd'hui (depuis minuit)
      startOfPeriod.setHours(0, 0, 0, 0)
      break
    case 'week':
      // 7 derniers jours
      startOfPeriod.setDate(now.getDate() - 7)
      break
    case 'month':
      // 30 derniers jours
      startOfPeriod.setDate(now.getDate() - 30)
      break
    case 'year':
      // 365 derniers jours
      startOfPeriod.setDate(now.getDate() - 365)
      break
  }

  return orders.filter(order => {
    const orderDate = new Date(order.saleDate)
    return orderDate >= startOfPeriod
  })
}

